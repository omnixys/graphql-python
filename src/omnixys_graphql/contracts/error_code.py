ERROR_CODES: tuple[ErrorCode, ...] = tuple(ErrorCode)

_ERROR_CODE_VALUES: frozenset[str] = frozenset(code.value for code in ErrorCode)


def is_error_code(value: object) -> bool:
    """Return ``True`` when ``value`` is one of the registered error codes."""
    return isinstance(value, str) and value in _ERROR_CODE_VALUES
